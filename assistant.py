def scheduler_loop(loop):
    global SYSTEM_ALARMS, SYSTEM_TIMERS, RUNNING, IS_SHUTTING_DOWN
    while RUNNING and not IS_SHUTTING_DOWN:
        now = datetime.datetime.now()
        current_time = now.time().replace(second=0, microsecond=0)
        current_timestamp = time.time()
        
        triggered_alarms = []
        for alarm in SYSTEM_ALARMS[:]:
            if alarm["time"] == current_time:
                triggered_alarms.append(alarm)
                SYSTEM_ALARMS.remove(alarm)

        for alarm in triggered_alarms:
            label = alarm.get("label", "Alarm")
            time_str = alarm["time"].strftime("%I:%M %p")
            asyncio.run_coroutine_threadsafe(
                speak(f"Attention Boss! {label} set for {time_str} is going off."), loop
            )

        triggered_timers = []
        for tmr in SYSTEM_TIMERS[:]:
            if current_timestamp >= tmr["end_time"]:
                triggered_timers.append(tmr)
                SYSTEM_TIMERS.remove(tmr)

        for tmr in triggered_timers:
            label = tmr.get("label", "Timer")
            asyncio.run_coroutine_threadsafe(
                speak(f"Attention Boss! Your {label} has finished."), loop
            )

        time.sleep(1)


