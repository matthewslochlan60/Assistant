def clean_text_for_speech(text_script: str) -> str:
    """Pre-processes and cleans text output for smooth voice synthesis."""
    text = re.sub(r'\*+([^*]+)\*+', r'\1', text_script)
    text = re.sub(r'`([^`]+)`', r'\1', text)
    text = re.sub(r'#+\s*', '', text)
    text = text.replace("&", "and").replace("%", "percent").replace("$", "dollars ")
    text = re.sub(r'\be\.g\.', 'for example', text, flags=re.IGNORECASE)
    text = re.sub(r'\bi\.e\.', 'that is', text, flags=re.IGNORECASE)
    return text.strip()

async def generate_elevenlabs_speech(text_script: str, output_filepath: str = "speech.mp3") -> bool:
    api_key = os.getenv("ELEVENLABS_API_KEY")
    if not api_key:
        return False
    voice_id = os.getenv("ELEVENLABS_VOICE_ID", "21m00Tcm4TlvDq8ikWAM")
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{voice_id}"
    headers = {
        "Accept": "audio/mpeg",
        "Content-Type": "application/json",
        "xi-api-key": api_key
    }
    payload = {
        "text": text_script,
        "model_id": "eleven_multilingual_v2",
        "voice_settings": {"stability": 0.5, "similarity_boost": 0.75}
    }
    try:
        response = await asyncio.to_thread(requests.post, url, json=payload, headers=headers)
        if response.status_code == 200:
            with open(output_filepath, "wb") as f:
                f.write(response.content)
            return True
    except Exception as e:
        print(f"ElevenLabs TTS Error: {e}")
    return False

async def generate_openai_speech(text_script: str, output_filepath: str = "speech.mp3", voice: str = "onyx") -> bool:
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        return False
    try:
        client = OpenAI(api_key=api_key)
        response = await asyncio.to_thread(
            client.audio.speech.create,
            model="tts-1-hd",
            voice=voice,
            input=text_script
        )
        response.stream_to_file(output_filepath)
        return True
    except Exception as e:
        print(f"OpenAI TTS Error: {e}")
    return False

def speak_locally(text_script: str, rate: int = 175, voice_index: int = 0):
    try:
        engine = pyttsx3.init()
        engine.setProperty('rate', rate)
        voices = engine.getProperty('voices')
        if voices:
            engine.setProperty('voice', voices[voice_index].id)
        engine.say(text_script)
        engine.runAndWait()
    except Exception as e:
        print(f"Local TTS Error: {e}")

