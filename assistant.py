# --- FASTER-WHISPER AUDIO CAPTURE ENGINE ---
def listen():
    """Captures microphone audio and processes through GPU-accelerated Faster-Whisper."""
    samplerate = 16000
    duration = 4  # Record in 4-second continuous windows
    
    try:
        audio_data = sd.rec(int(duration * samplerate), samplerate=samplerate, channels=1, dtype='int16')
        sd.wait()

        # Check if ambient noise floor is silent to avoid unnecessary GPU passes
        max_amplitude = np.max(np.abs(audio_data))
        if max_amplitude < 500:
            return ""

        temp_wav = os.path.join(tempfile.gettempdir(), "moloch_mic_input.wav")
        wav.write(temp_wav, samplerate, audio_data)

        segments, _ = whisper_pipeline.transcribe(
            temp_wav,
            batch_size=16,
            language="en",
            initial_prompt="System assistant wake commands, WhatsApp, Discord, link start, moloch.",
            vad_filter=True,
            vad_parameters=dict(min_silence_duration_ms=400, speech_pad_ms=150),
            beam_size=5,
            condition_on_previous_text=False
        )

        full_text = "".join([segment.text for segment in segments]).strip()
        if full_text:
            add_gui_log(f"USER: {full_text}")
            return full_text.lower()

    except Exception as e:
        print(f"Faster-Whisper Capture Error: {e}")

    return ""


