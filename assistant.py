def parse_alarm_time(command):
    time_match = re.search(r'(\d{1,2})(?::(\d{2}))?\s*(am|pm)?', command, re.IGNORECASE)
    if not time_match:
        return None

    hour = int(time_match.group(1))
    minute = int(time_match.group(2)) if time_match.group(2) else 0
    meridiem = time_match.group(3)

    if meridiem:
        meridiem = meridiem.lower()
        if meridiem == "pm" and hour < 12:
            hour += 12
        elif meridiem == "am" and hour == 12:
            hour = 0

    if 0 <= hour <= 23 and 0 <= minute <= 59:
        return datetime.time(hour, minute)
    return None


def parse_timer_seconds(command):
    seconds = 0
    min_match = re.search(r'(\d+)\s*(minute|min|minutes)', command, re.IGNORECASE)
    sec_match = re.search(r'(\d+)\s*(second|sec|seconds)', command, re.IGNORECASE)
    
    if min_match:
        seconds += int(min_match.group(1)) * 60
    if sec_match:
        seconds += int(sec_match.group(1))
        
    return seconds if seconds > 0 else None


