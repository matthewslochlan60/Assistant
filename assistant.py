def play_procedural_sound(sound_type="boot"):
    """Generates pure audio frequency sweeps for futuristic UI sound design."""
    def sound_thread():
        try:
            pygame.mixer.init(frequency=44100, size=-16, channels=2)
            sample_rate = 44100
            duration = 0.4
            t = np.linspace(0, duration, int(sample_rate * duration), False)
            
            if sound_type == "boot":
                freq = np.linspace(220, 880, len(t))
            elif sound_type == "sleep":
                freq = np.linspace(660, 110, len(t))
            elif sound_type == "rest":
                freq = np.linspace(440, 330, len(t))
            elif sound_type == "wake":
                freq = np.linspace(330, 660, len(t))
            else:
                freq = np.ones(len(t)) * 440

            tone = np.sin(2 * np.pi * freq * t)
            audio = (tone * 32767 * 0.15).astype(np.int16)
            stereo_audio = np.column_stack((audio, audio))
            sound = pygame.sndarray.make_sound(stereo_audio)
            sound.play()
            time.sleep(duration)
        except Exception as e:
            print(f"Audio Synth Error: {e}")

    threading.Thread(target=sound_thread, daemon=True).start()


